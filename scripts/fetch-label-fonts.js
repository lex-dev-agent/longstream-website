#!/usr/bin/env node
// Fetch the label fonts from Google Fonts into labels/fonts/, and write the
// @font-face rules that go with them to labels/fonts.css.
//
//   node scripts/fetch-label-fonts.js
//
// Run this only when a weight is added to labels/label.css. The files it
// downloads are committed, so a render never touches the network.
//
// Two things here are not optional, and both cost an afternoon to rediscover:
//
//   1. STATIC INSTANCES, one file per weight. Chrome renders a variable font
//      correctly on screen but will not embed it when printing to PDF — it
//      silently substitutes Georgia and Segoe UI, and the only symptom is a
//      proof that looks subtly wrong. Asking for a single weight
//      (`css2?family=Jost:wght@500`) returns a static instance; asking for
//      several at once returns the variable font.
//
//   2. BOTH SUBSETS. Google splits each face into `latin` (ASCII and friends)
//      and `latin-ext`. They are disjoint: latin-ext holds the macron vowels
//      and nothing else, so a label set in latin-ext alone renders entirely in
//      the fallback font, and one set in latin alone loses the ā in Māori.

const fs = require('fs');
const path = require('path');

const FONTS = path.join(__dirname, '..', 'labels', 'fonts');
const CSS = path.join(__dirname, '..', 'labels', 'fonts.css');
const SUBSETS = ['latin', 'latin-ext'];

// A modern UA is what makes Google serve woff2 rather than ttf.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FACES = [
  { family: 'Playfair Display', weight: 400, style: 'normal', slug: 'playfair-400' },
  { family: 'Playfair Display', weight: 600, style: 'normal', slug: 'playfair-600' },
  { family: 'Playfair Display', weight: 400, style: 'italic', slug: 'playfair-400-italic' },
  { family: 'Jost', weight: 400, style: 'normal', slug: 'jost-400' },
  { family: 'Jost', weight: 500, style: 'normal', slug: 'jost-500' },
  { family: 'Jost', weight: 600, style: 'normal', slug: 'jost-600' },
  { family: 'Jost', weight: 700, style: 'normal', slug: 'jost-700' }
];

function apiUrl({ family, weight, style }) {
  const name = family.replace(/ /g, '+');
  const spec = style === 'italic' ? `ital,wght@1,${weight}` : `wght@${weight}`;
  return `https://fonts.googleapis.com/css2?family=${name}:${spec}&display=block`;
}

// Pull one { subset -> { url, range } } map out of a Google Fonts stylesheet.
// Each face is preceded by a /* subset */ comment naming it.
function parseFaces(css) {
  const out = {};
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const url = /url\((https:[^)]+)\)/.exec(m[2]);
    const range = /unicode-range:\s*([^;]+);/.exec(m[2]);
    if (url && range) out[m[1]] = { url: url[1], range: range[1].trim() };
  }
  return out;
}

async function get(url, asText) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return asText ? res.text() : Buffer.from(await res.arrayBuffer());
}

(async () => {
  fs.mkdirSync(FONTS, { recursive: true });
  const rules = [];

  for (const face of FACES) {
    const found = parseFaces(await get(apiUrl(face), true));

    for (const subset of SUBSETS) {
      const entry = found[subset];
      if (!entry) throw new Error(`${face.slug}: Google served no "${subset}" subset`);

      const file = `${face.slug}-${subset}.woff2`;
      const buf = await get(entry.url, false);

      // A variable font carries an 'fvar' table. If one turns up here, the
      // single-weight request stopped returning a static instance and the
      // PDFs will quietly lose their typefaces.
      if (buf.includes(Buffer.from('fvar'))) {
        throw new Error(`${file} is a variable font — see the note at the top of this script`);
      }

      fs.writeFileSync(path.join(FONTS, file), buf);
      rules.push(
        `@font-face {\n` +
        `  font-family: '${face.family}';\n` +
        `  src: url('fonts/${file}') format('woff2');\n` +
        `  font-weight: ${face.weight};\n` +
        `  font-style: ${face.style};\n` +
        `  unicode-range: ${entry.range};\n` +
        `}`
      );
      console.log(`${file.padEnd(34)} ${String(buf.length).padStart(6)} bytes`);
    }
  }

  fs.writeFileSync(CSS,
    '/* Generated by scripts/fetch-label-fonts.js — do not edit by hand.\n' +
    '   Two faces per weight: `latin` carries the ASCII, `latin-ext` carries\n' +
    '   the macron vowels. Both are needed. */\n\n' + rules.join('\n\n') + '\n');
  console.log(`\nwrote labels/fonts.css (${rules.length} faces)`);
})();
